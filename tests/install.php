function check(string $what, bool $ok, string $detail = ''): void
{
	global $failures;
	echo ($ok ? '  ok      ' : '  FAIL    ') . $what . ($ok || $detail === '' ? '' : " - $detail") . "\n";
	if (!$ok) {
		$failures++;
	}
}

/**
 * Runs a command; kills it after 30 seconds (exit code -1), so a hanging
 * installer fails the test instead of blocking it.
 *
 * @return array{0: int, 1: string} exit code, combined output
 */
function run(string ...$command): array
{
	$process = proc_open($command, [0 => ['file', '/dev/null', 'r'], 1 => ['pipe', 'w'], 2 => ['redirect', 1]], $pipes);
	stream_set_blocking($pipes[1], false);
	$output = '';
	$deadline = microtime(true) + 30;
	while (true) {
		$output .= (string)stream_get_contents($pipes[1]);
		$status = proc_get_status($process);
		if (!$status['running']) {
			$output .= (string)stream_get_contents($pipes[1]);
			fclose($pipes[1]);
			proc_close($process);
			return [$status['exitcode'], $output];
		}
		if (microtime(true) > $deadline) {
			proc_terminate($process, 9);
			fclose($pipes[1]);
			proc_close($process);
			exec('pkill -9 -f agency-stubs 2>/dev/null');
			return [-1, $output . "\n(timeout)"];
		}
		usleep(20000);
	}
}

/** Creates a minimal fake Froxlor with the given templates; returns its path. */
function fakeFroxlor(string $name, array $templates): string
{
	$dir = sys_get_temp_dir() . '/agency-install-test-' . getmypid() . '-' . $name;
	mkdir("$dir/lib", 0777, true);
	mkdir("$dir/cache", 0777, true);
	file_put_contents("$dir/lib/init.php", "<?php\n");
	foreach ($templates as $rel) {
		@mkdir(dirname("$dir/templates/Froxlor/$rel"), 0777, true);
		file_put_contents("$dir/templates/Froxlor/$rel", "{# template #}\n");
	}
	return $dir;
}

function fileMode(string $path): string
{
	clearstatcache();
	return sprintf('%04o', fileperms($path) & 0777);
}

/** @return list<string> relative paths of all *.twig files below $dir */
function twigFiles(string $dir): array
{
	$files = [];
	if (!is_dir($dir)) {
		return $files;
	}
	$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
	foreach ($it as $file) {
		if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
			$files[] = substr($file->getPathname(), strlen($dir) + 1);
		}
	}
	sort($files);
	return $files;
}

/** Fingerprint of every file outside the theme's own paths. */
function froxlorFiles(string $dir): array
{
	$sums = [];
	$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
	foreach ($it as $file) {
		$rel = substr($file->getPathname(), strlen($dir) + 1);
		if ($file->isFile() && !str_starts_with($rel, 'templates/Agency/') && $rel !== 'theme_agency.php' && !str_starts_with($rel, 'cache/')) {
			$sums[$rel] = md5_file($file->getPathname());
		}
	}
	ksort($sums);
	return $sums;
}

